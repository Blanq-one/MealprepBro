def i(
    slug: str, quantity: str | int, unit: str, role: str, prep: str | None = None, **extra: Any
) -> dict[str, Any]:
    line: dict[str, Any] = {"ingredient": slug, "quantity": str(quantity), "unit": unit}
    if prep:
        line["preparation"] = prep
    line["role"] = role
    line.update(extra)
    return line


def s(
    section: str, text: str, minutes: int | None = None, temp: int | None = None, check: str | None = None
) -> dict[str, Any]:
    step: dict[str, Any] = {"section": section, "text": text}
    if minutes is not None:
        step["duration_minutes"] = minutes
    if temp is not None:
        step["appliance_temp_f"] = temp
    if check is not None:
        step["doneness_check_for"] = check
    return step


def SALT(q: str = "1") -> dict[str, Any]:  # noqa: N802 - reads like the other shared lines
    return i("salt", q, "tsp", "seasoning")


def PEPPER(q: str = "1/2") -> dict[str, Any]:  # noqa: N802
    return i("black-pepper", q, "tsp", "seasoning")


